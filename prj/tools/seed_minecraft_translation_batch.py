def _queue_path(book: int, queue: Path | None) -> Path:
    return Path(queue) if queue else QUEUE_DIR / f"book{book}.json"


def apply_batch(book: int, translations: list[str], queue: Path | None = None) -> Path:
    path = _queue_path(book, queue)
    payload = json.loads(path.read_text(encoding="utf-8"))
    records = payload.get("sentences")
    if not isinstance(records, list) or len(records) != len(translations):
        raise ValueError(f"book{book}: queue has {len(records or [])} records, expected {len(translations)}")
    source_path = REPO / "prj" / "data" / "storybooks-minecraft" / f"sentence-annotations-book{book}.json"
    source_payload = json.loads(source_path.read_text(encoding="utf-8"))
    source_records = source_payload.get("sentences")
    if not isinstance(source_records, list) or len(source_records) != len(records):
        raise ValueError(f"book{book}: queue/source record count mismatch")
    for index, (record, zh) in enumerate(zip(records, translations), start=1):
        if not isinstance(record, dict) or not record.get("id") or not record.get("text_en"):
            raise ValueError(f"book{book}: malformed record {index}")
        source = source_records[index - 1]
        if record.get("id") != source.get("id") or record.get("text_en") != source.get("text_en"):
            raise ValueError(f"book{book}: queue source mismatch at {record.get('id')}")
        if not zh.strip() or "TODO" in zh or "待翻译" in zh:
            raise ValueError(f"book{book}: empty/placeholder translation at {record.get('id')}")
        record["zh"] = zh.strip()
        record["status"] = "reviewed"
        record["reviewer_note"] = "Codex 逐句复核：与英文语义、角色名及 Minecraft 官方术语核对；保留引号内儿童口吻。"
    payload["status"] = "reviewed-batch-1"
    payload["reviewer"] = "codex"
    payload["review_scope"] = "book1 sentence-by-sentence semantic and terminology review"
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return path


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--book", type=int, choices=[1, 2, 3, 4, 5], default=1)
    parser.add_argument("--queue", type=Path)
    args = parser.parse_args(list(argv) if argv is not None else None)
    translations = {1: BOOK1_ZH, 2: BOOK2_ZH, 3: BOOK3_ZH, 4: BOOK4_ZH, 5: BOOK5_ZH}[args.book]
    print(apply_batch(args.book, translations, args.queue))
    return 0


